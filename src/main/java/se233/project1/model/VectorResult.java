package se233.project1.model;

import java.util.List;

/**
 * A traced image: color layers produced by Potrace, drawn bottom to top.
 * Potrace path coordinates are mapped into the traced bitmap by
 * {@code translate(potraceTx, potraceTy) scale(potraceSx, potraceSy)}; the traced bitmap is then scaled
 * up to the original image size.
 */
public class VectorResult {
    /** One filled shape group of a single color. */
    public static class Layer {
        private final int rgb;
        private final String pathData;

        public Layer(int rgb, String pathData) {
            this.rgb = rgb;
            this.pathData = pathData;
        }

        public int getRgb() { return rgb; }
        public String getPathData() { return pathData; }

        public String getHexColor() {
            return String.format("#%06x", rgb & 0xFFFFFF);
        }
    }

    private final int width, height, traceWidth, traceHeight;
    private final double potraceTx, potraceTy, potraceSx, potraceSy;
    private final List<Layer> layers;
    private final VectorSettings settings;
    private final long elapsedMillis;

    public VectorResult(int width, int height, int traceWidth, int traceHeight,
                        double potraceTx, double potraceTy, double potraceSx, double potraceSy,
                        List<Layer> layers, VectorSettings settings, long elapsedMillis) {
        this.width = width;
        this.height = height;
        this.traceWidth = traceWidth;
        this.traceHeight = traceHeight;
        this.potraceTx = potraceTx;
        this.potraceTy = potraceTy;
        this.potraceSx = potraceSx;
        this.potraceSy = potraceSy;
        this.layers = layers;
        this.settings = settings;
        this.elapsedMillis = elapsedMillis;
    }

    public int getWidth() { return width; }
    public int getHeight() { return height; }
    public double getPotraceTx() { return potraceTx; }
    public double getPotraceTy() { return potraceTy; }
    public double getPotraceSx() { return potraceSx; }
    public double getPotraceSy() { return potraceSy; }
    public List<Layer> getLayers() { return layers; }
    public VectorSettings getSettings() { return settings; }
    public long getElapsedMillis() { return elapsedMillis; }

    public double getScaleX() { return width / (double) traceWidth; }
    public double getScaleY() { return height / (double) traceHeight; }

    public String toSvg() {
        String svg = "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"no\"?>\n";
        svg += String.format("<svg xmlns=\"http://www.w3.org/2000/svg\" version=\"1.1\" width=\"%d\" height=\"%d\" viewBox=\"0 0 %d %d\">\n",
                width, height, width, height);
        svg += "<!-- Generated by SE233 Vectorizer (Potrace). " + settings.describe() + " -->\n";
        svg += "<g transform=\"scale(" + getScaleX() + "," + getScaleY() + ") translate(" + potraceTx + ","
                + potraceTy + ") scale(" + potraceSx + "," + potraceSy + ")\" stroke=\"none\">\n";
        for (Layer layer : layers) {
            svg += "<path fill=\"" + layer.getHexColor() + "\" d=\"" + layer.getPathData() + "\"/>\n";
        }
        svg += "</g>\n</svg>\n";
        return svg;
    }

    public int getSvgSizeBytes() {
        return toSvg().length();
    }
}
